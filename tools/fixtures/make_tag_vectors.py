"""Emit the tag dump fixtures as C arrays in flipper/tests/vectors/tag_dumps.h.

The C encoder tests build a `TagDump` from these arrays and compare the
encoded `scan` line with protocol/fixtures/messages/scan_*.json, so the
header carries the raw bytes of the Bambu and NTAG dumps plus the scan ids
and missing sectors that `make_message_fixtures` used.
`tests/test_tag_vectors.py` fails when the header is stale.

Run from tools/ after the tag and message generators:
`uv run python -m fixtures.make_tag_vectors`.
"""

import json
from pathlib import Path

from fixtures import PROTOCOL, make_bambu_dump, make_message_fixtures, make_ntag_dump

REPO = Path(__file__).resolve().parents[2]
OUTPUT = "flipper/tests/vectors/tag_dumps.h"


def load_tag(relative: str) -> dict:
    return json.loads((PROTOCOL / relative).read_text(encoding="utf-8"))


def c_row(data: bytes) -> str:
    return "{" + ",".join(f"0x{b:02X}" for b in data) + "}"


def c_rows(rows: list[str]) -> list[str]:
    return [f"    {c_row(bytes.fromhex(row))}," for row in rows]


def render() -> str:
    mfc = load_tag(make_bambu_dump.OUTPUT)
    ntag = load_tag(make_ntag_dump.OUTPUT)
    mfc_uid = bytes.fromhex(mfc["uid"])
    ntag_uid = bytes.fromhex(ntag["uid"])
    missing = make_message_fixtures.MISSING_SECTORS

    out = [
        "/* Generated by tools/fixtures/make_tag_vectors.py; do not edit. */",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        f"/* {make_bambu_dump.OUTPUT}, encoded as fixtures/messages/scan_mfc.json */",
        f'#define MFC_SCAN_ID "{make_message_fixtures.MFC_SCAN_ID}"',
        f"#define MFC_SAK {mfc['sak']}",
        f"static const uint8_t MFC_UID[{len(mfc_uid)}] = {c_row(mfc_uid)};",
        f"static const uint8_t MFC_ATQA[2] = {c_row(bytes.fromhex(mfc['atqa']))};",
        f"static const uint8_t MFC_MISSING_SECTORS[{len(missing)}] = "
        "{" + ", ".join(str(s) for s in missing) + "};",
        f"static const uint8_t MFC_BLOCKS[{len(mfc['blocks'])}][16] = {{",
        *c_rows(mfc["blocks"]),
        "};",
        "",
        f"/* {make_ntag_dump.OUTPUT}, encoded as fixtures/messages/scan_ntag.json */",
        f'#define NTAG_SCAN_ID "{make_message_fixtures.NTAG_SCAN_ID}"',
        f"#define NTAG_SAK {ntag['sak']}",
        f"static const uint8_t NTAG_UID[{len(ntag_uid)}] = {c_row(ntag_uid)};",
        f"static const uint8_t NTAG_ATQA[2] = {c_row(bytes.fromhex(ntag['atqa']))};",
        f"static const uint8_t NTAG_PAGES[{len(ntag['pages'])}][4] = {{",
        *c_rows(ntag["pages"]),
        "};",
        "",
        "#define MFC_MISSING_COUNT (sizeof(MFC_MISSING_SECTORS) / sizeof(MFC_MISSING_SECTORS[0]))",
        "#define NTAG_PAGE_COUNT (sizeof(NTAG_PAGES) / sizeof(NTAG_PAGES[0]))",
    ]
    return "\n".join(out) + "\n"


def build() -> dict[str, str]:
    return {OUTPUT: render()}


if __name__ == "__main__":
    for relative, content in build().items():
        path = REPO / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {relative}")
