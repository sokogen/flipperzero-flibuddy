"""Emit the Flipper app's icons as XBM files in flipper/images/.

The bitmaps come from the `I` table of the design prototype
(docs/design/source/flipper-ui.js), rows of '#' (ink) and '.' (paper).
XBM packs each row LSB first into whole bytes, which is the layout
`canvas_draw_xbm` expects; flipper/src/ui_icons.c includes the files.
The canvas does not scale bitmaps, so the About screen's double-size app
icon is generated as `app_2x`. `tests/test_flipper_icons.py` fails when a
file is stale.

Run from tools/: `uv run python -m fixtures.make_flipper_icons`.
"""

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DESIGN = REPO / "docs" / "design" / "source" / "flipper-ui.js"
OUTPUT_DIR = "flipper/images"

# file name -> key in the design's icon table
ICONS = {
    "usb": "usb",
    "bt": "bt",
    "check": "check",
    "warn": "warn",
    "arrow_left": "aL",
    "arrow_right": "aR",
    "arrow_up": "aU",
    "arrow_down": "aD",
    "app": "app",
}


def load_bitmaps(path: Path = DESIGN) -> dict[str, list[str]]:
    """The `const I = {...};` table of the prototype."""
    block = re.search(
        r"^const I = \{\n(.*?)^\};",
        path.read_text(encoding="utf-8"),
        re.MULTILINE | re.DOTALL,
    )
    if block is None:
        raise ValueError(f"no icon table in {path}")
    bitmaps = {}
    for line in block.group(1).splitlines():
        entry = re.match(r"\s*(\w+): \[(.*)\],?$", line)
        if entry:
            bitmaps[entry.group(1)] = re.findall(r"'([.#]+)'", entry.group(2))
    return bitmaps


def scale(rows: list[str], factor: int) -> list[str]:
    return ["".join(ch * factor for ch in row) for row in rows for _ in range(factor)]


def pack_row(row: str) -> list[int]:
    out = []
    for start in range(0, len(row), 8):
        byte = 0
        for bit, ch in enumerate(row[start : start + 8]):
            if ch == "#":
                byte |= 1 << bit
        out.append(byte)
    return out


def xbm(name: str, rows: list[str]) -> str:
    width = len(rows[0])
    if any(len(row) != width for row in rows):
        raise ValueError(f"{name}: uneven rows")
    data = [b for row in rows for b in pack_row(row)]
    lines = [
        "/* Generated by tools/fixtures/make_flipper_icons.py; do not edit. */",
        f"#define {name}_width {width}",
        f"#define {name}_height {len(rows)}",
        f"static const unsigned char {name}_bits[] = {{",
    ]
    for start in range(0, len(data), 12):
        lines.append("    " + " ".join(f"0x{b:02x}," for b in data[start : start + 12]))
    lines.append("};")
    return "\n".join(lines) + "\n"


def build() -> dict[str, str]:
    bitmaps = load_bitmaps()
    icons = {name: bitmaps[key] for name, key in ICONS.items()}
    icons["app_2x"] = scale(bitmaps["app"], 2)
    return {f"{OUTPUT_DIR}/{name}.xbm": xbm(name, rows) for name, rows in icons.items()}


if __name__ == "__main__":
    for relative, content in build().items():
        path = REPO / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {relative}")
