"""Bambu colour codes: `tools/data/bambu_color_codes.json` and its Swift twin.

Bambu tags do not carry the five-digit colour code printed on the box
(`11803` for PLA Matte Caramel). Bambu Studio maps it from the tag's
filament id (block 1, `GFA01`) and the colour part of its variant id
(`A01-N3` -> `N3`) in `resources/profiles/BBL/filament/filaments_color_codes.json`.
This script keeps the facts the host needs from that file: filament id,
colour id, code, English name and the first colour as RRGGBB.

Refresh the data from a downloaded Bambu Studio file, then regenerate:

    uv run python -m fixtures.make_color_codes --source filaments_color_codes.json
    uv run python -m fixtures.make_color_codes

It also writes the same rows as a packed C table for the Flipper, which
names the colour of a tag read without the app (flipper/src/bambu_colors.h):
each name stored once, a row of 12 bytes (filament and name indexes, colour
id, RGB, the code as 24 bits).

`tests/test_color_codes.py` fails when the Swift or C file is stale.
"""

import argparse
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DATA = "tools/data/bambu_color_codes.json"
SWIFT = "host/Sources/FliBuddyCore/Tags/BambuColorCodes.swift"
C_HEADER = "flipper/src/bambu_color_table.h"


def trim(source: dict) -> list[dict]:
    """The rows of a Bambu Studio `filaments_color_codes.json`, trimmed."""
    rows = []
    for item in source["data"]:
        name = item.get("fila_color_name", {}).get("en")
        colors = item.get("fila_color") or []
        if not (item.get("fila_id") and item.get("color_code") and item.get("fila_color_code") and name):
            continue
        rows.append({
            "filament_id": item["fila_id"],
            "color_id": item["color_code"],
            "code": item["fila_color_code"],
            "name": name,
            "rgb": colors[0].lstrip("#")[:6].upper() if colors else "",
        })
    rows.sort(key=lambda r: (r["filament_id"], r["color_id"]))
    return rows


def load() -> list[dict]:
    return json.loads((REPO / DATA).read_text(encoding="utf-8"))


def _swift_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _c_table(rows: list[dict]) -> str:
    filaments = sorted({r["filament_id"] for r in rows})
    names = sorted({r["name"] for r in rows})
    for r in rows:
        assert r["name"].isascii() and '"' not in r["name"] and "\\" not in r["name"], r
        assert r["code"].isdigit() and not r["code"].startswith("0") and int(r["code"]) < 1 << 24, r
        assert len(r["color_id"]) <= 3 and len(r["filament_id"]) == 5 and len(r["rgb"]) == 6, r
    assert len(filaments) < 256 and len(names) < 256
    offsets, at = [], 0
    for name in names:
        offsets.append(at)
        at += len(name) + 1
    lines = [
        "/* Generated by tools/fixtures/make_color_codes.py from",
        " * tools/data/bambu_color_codes.json (facts from Bambu Studio's",
        " * filaments_color_codes.json). Do not edit; bambu_colors.c includes it. */",
        "#pragma once",
        "",
        f"#define BAMBU_COLOR_ROWS {len(rows)}",
        "",
        f"static const char bambu_color_filaments[{len(filaments)}][6] = {{",
        *[f'    "{f}",' for f in filaments],
        "};",
        "",
        "/* The English names, each ended by a NUL; bambu_color_name_at[i] is",
        " * where name i starts. */",
        "static const char bambu_color_names[] =",
        *[f'    "{n}\\0"' for n in names],
        "    ;",
        "",
        f"static const uint16_t bambu_color_name_at[{len(names)}] = {{",
    ]
    for start in range(0, len(offsets), 12):
        lines.append("    " + " ".join(f"{o}," for o in offsets[start : start + 12]))
    lines += [
        "};",
        "",
        "/* One colour each: indexes into the tables above, the colour id, RGB and",
        " * the code (24 bits, little endian), in the order of the JSON, as in the",
        " * host's table, so that the first match is the same on both sides. */",
        "static const BambuColorRow bambu_color_rows[BAMBU_COLOR_ROWS] = {",
    ]
    for r in rows:
        rgb = ", ".join(f"0x{r['rgb'][i:i + 2]}" for i in (0, 2, 4))
        code = int(r["code"])
        code_bytes = ", ".join(f"0x{(code >> (8 * i)) & 0xFF:02X}" for i in range(3))
        lines.append(
            f'    {{.filament = {filaments.index(r["filament_id"])}, .name = {names.index(r["name"])}, '
            f'.color = "{r["color_id"]}", .rgb = {{{rgb}}}, .code = {{{code_bytes}}}}},'
        )
    lines += ["};", ""]
    return "\n".join(lines)


def build() -> dict[str, str]:
    rows = load()
    lines = [
        "// Generated by tools/fixtures/make_color_codes.py from",
        "// tools/data/bambu_color_codes.json (facts from Bambu Studio's",
        "// filaments_color_codes.json). Do not edit.",
        "",
        "/// One Bambu colour: filament id and colour id as on the tag, the code",
        "/// printed on the box, the English name and the colour as RRGGBB.",
        "public struct BambuColorCode: Equatable, Sendable {",
        "    public let filamentId: String",
        "    public let colorId: String",
        "    public let code: String",
        "    public let name: String",
        "    public let rgb: String",
        "}",
        "",
        "extension BambuColorCode {",
        "    static let all: [BambuColorCode] = [",
    ]
    for r in rows:
        args = ", ".join(
            f"{key}: {_swift_string(r[field])}"
            for key, field in (("filamentId", "filament_id"), ("colorId", "color_id"),
                               ("code", "code"), ("name", "name"), ("rgb", "rgb"))
        )
        lines.append(f"        BambuColorCode({args}),")
    lines += ["    ]", "}", ""]
    return {SWIFT: "\n".join(lines), C_HEADER: _c_table(rows)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, help="Bambu Studio filaments_color_codes.json")
    args = parser.parse_args()
    if args.source:
        rows = trim(json.loads(args.source.read_text(encoding="utf-8")))
        (REPO / DATA).write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        print(f"wrote {DATA}: {len(rows)} colours")
    for relative, content in build().items():
        (REPO / relative).write_text(content, encoding="utf-8")
        print(f"wrote {relative}")


if __name__ == "__main__":
    main()
